import { computeStreak } from '../js/features/reto/streak/compute-streak.js';
import { spainDay, addDays } from '../js/features/reto/streak/date-keys.js';
import { mondayOf } from '../js/features/reto/streak/week-start.js';
let ok = 0, bad = 0;
const eq = (name, got, want) => { if (got === want) { ok++; console.log('✓', name); } else { bad++; console.log('✗', name, 'obtenido', got, 'esperado', want); } };
const d = (...days) => days.map((n) => `2026-10-${String(n).padStart(2, '0')}`);
const T = (n) => `2026-10-${String(n).padStart(2, '0')}`;

eq('sin días → 0', computeStreak([], T(26)), 0);
eq('semana completa, hoy pendiente → 7', computeStreak(d(19,20,21,22,23,24,25), T(26)), 7);
eq('semana completa y hoy hecho → 8', computeStreak(d(19,20,21,22,23,24,25,26), T(26)), 8);
eq('solo hoy hecho → 1', computeStreak(d(26), T(26)), 1);
eq('un fallo (cortesía) no rompe', computeStreak(d(19,20,22), T(22)), 3);
eq('dos fallos en la misma semana reinician', computeStreak(d(19,22), T(22)), 1);
eq('fallo domingo + lunes: cada semana su cortesía', computeStreak(d(19,20,21,22,23,24,27), T(27)), 7);
eq('domingo+lunes+martes fallados reinicia', computeStreak(d(19,20,21,22,23,24,28), T(28)), 1);
eq('cortesía se renueva cada lunes (12 seguidos)', computeStreak(d(12,14,15,16,17,18,19,21,22,23,24,25), T(26)), 12);
eq('mucho tiempo sin hacerlo → 0', computeStreak(d(1,2,3), T(26)), 0);
eq('ayer fallado, hoy pendiente (cortesía) conserva', computeStreak(d(22,23,24), T(26)), 3);
eq('dos días fallados, hoy pendiente → 0', computeStreak(d(22,23), T(26)), 0);
eq('entrada desordenada y duplicada', computeStreak(d(21,19,20,20,19), T(21)), 3);
eq('tras reiniciar se empieza de nuevo', computeStreak(d(12,13,17,18,19), T(19)), 3);
eq('mondayOf domingo', mondayOf('2026-10-25'), '2026-10-19');
eq('mondayOf lunes', mondayOf('2026-10-26'), '2026-10-26');
eq('mondayOf miércoles', mondayOf('2026-10-21'), '2026-10-19');
eq('addDays cruza el cambio de hora', addDays('2026-10-24', 2), '2026-10-26');
eq('addDays cruza el mes', addDays('2026-10-31', 1), '2026-11-01');
eq('spainDay 23:30 España (22:30Z) → mismo día', spainDay(new Date('2026-10-25T22:30:00Z')), '2026-10-25');
eq('spainDay 00:30 España (23:30Z) → día siguiente', spainDay(new Date('2026-10-25T23:30:00Z')), '2026-10-26');
eq('spainDay verano 00:30 (22:30Z)', spainDay(new Date('2026-07-14T22:30:00Z')), '2026-07-15');
console.log(`\n${ok} ✓, ${bad} ✗`);
process.exit(bad ? 1 : 0);
